test('TC11 checkout validates address, payment and promotion before placing the order', async ({ page }) => {
  await seedCart(page, [line(tee, 'white', 'S', 2)])
  const state = await setup(page, { signedIn: true, addresses: [] })
  await page.goto('/checkout')
  const place = page.getByRole('button', { name: 'Place order' })
  await expect(page.getByText('Add a delivery address to continue.')).toBeVisible()
  await expect(place).toBeDisabled()
  // Mã giảm giá không hợp lệ
  await page.getByLabel('Promotion code').fill('nope')
  await page.getByRole('button', { name: 'Apply' }).click()
  await expect(page.getByRole('alert').filter({ hasText: /Code unavailable|no longer active/ })).toBeVisible()
  // Thêm địa chỉ: số điện thoại sai bị chặn, dữ liệu đúng mới được gửi
  await page.getByRole('button', { name: 'Choose address' }).click()
  await page.getByRole('button', { name: '+ Add new address' }).click()
  const form = page.getByRole('dialog', { name: 'Add new address' })
  await form.getByLabel(/Full name/).fill('QA buyer')
  await form.getByLabel(/Email/).fill('buyer@example.invalid')
  await form.getByLabel(/Phone number/).fill('12345')
  await form.getByLabel(/City \/ Province/).fill('Hà Nội')
  await form.getByLabel(/Street address/).fill('1 QA street')
  await form.getByRole('button', { name: 'Save address' }).click()
  expect(await form.getByLabel(/Phone number/).evaluate(input => input.validity.valid)).toBe(false)
  expect(state.addressPosts).toEqual([])
  await form.getByLabel(/Phone number/).fill('0901234567')
  await form.getByRole('button', { name: 'Save address' }).click()
  await expect.poll(() => state.addressPosts.length).toBe(1)
  expect(state.addressPosts[0].address).toMatchObject({ name: 'QA buyer', phone: '0901234567', city: 'Hà Nội' })
  await page.getByRole('button', { name: 'Confirm address' }).click()
  await expect(place).toBeEnabled()
  // Chưa chọn phương thức thanh toán → mở hộp chọn, chưa gửi đơn
  await place.click()
  await expect(page.getByRole('dialog', { name: 'Choose payment method' })).toBeVisible()
  expect(state.orders).toEqual([])
  await page.getByRole('button', { name: 'Confirm', exact: true }).click()
  await expect(page.getByText('Please select a payment method.')).toHaveCount(0)
  await place.click()
  await expect(page.getByRole('heading', { name: 'Order placed' })).toBeVisible()
  expect(state.orders).toHaveLength(1)
  expect(state.orders[0]).toMatchObject({ payment: 'cod', address_id: '44444444-4444-4444-8444-444444444444', items: [{ product_id: 11, color: 'white', size: 'S', quantity: 2, expected_price: 250000 }] })
  expect(state.orders[0].request_id).toBeTruthy()
  await expect(page.getByText(money(500000))).toBeVisible()
  expect(await cartLines(page)).toEqual([])
  await expect(page.getByRole('link', { name: 'Cart, 0 items' })).toBeVisible()
  await state.verify()
})

