test('TC08 & TC10 add-to-bag stores the exact variant and the bag survives a reload', async ({ page }) => {
  const state = await setup(page, { signedIn: true })
  await page.goto('/product/11')
  await page.getByRole('button', { name: 'Pearl white', exact: true }).click()
  await page.getByRole('button', { name: 'S', exact: true }).click()
  await page.getByRole('button', { name: 'Increase quantity' }).click()
  await page.getByRole('button', { name: 'Add to bag' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Added to your bag.' })).toBeVisible()
  expect(await cartLines(page)).toEqual([{ id: 11, color: 'white', size: 'S', quantity: 2 }])
  await expect(page.getByRole('link', { name: 'Cart, 2 items' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('link', { name: 'Cart, 2 items' })).toBeVisible()
  await page.getByRole('link', { name: 'View bag' }).or(page.getByRole('link', { name: 'Cart, 2 items' })).first().click()
  await expect(page).toHaveURL(/\/cart$/)
  await expect(page.getByRole('link', { name: 'QA tee', exact: true })).toBeVisible()
  await expect(page.getByText('Pearl white / S')).toBeVisible()
  expect(await cartLines(page)).toEqual([{ id: 11, color: 'white', size: 'S', quantity: 2 }])
  await state.verify()
})

