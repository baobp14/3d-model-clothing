test('TC13 protected routes redirect guests to sign-in and back; admins stay out of the shop', async ({ page }) => {
  const state = await setup(page)
  for (const path of ['/cart', '/checkout', '/account/orders', '/account/wishlist', '/account/addresses']) {
    await page.goto(path)
    await expect(page).toHaveURL(new RegExp(`/login\\?next=${encodeURIComponent(path).replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}$`))
  }
  await page.goto('/admin')
  await expect(page).not.toHaveURL(/\/admin/)
  await page.goto('/login?next=%2Fcart')
  await page.getByRole('textbox', { name: 'Email', exact: true }).fill('buyer@example.invalid')
  await page.getByRole('textbox', { name: 'Password', exact: true }).fill('isolated-test-password')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page).toHaveURL(/\/cart$/)
  await expect(page.getByRole('heading', { name: 'Your bag is empty.' })).toBeVisible()
  await state.verify()
})

