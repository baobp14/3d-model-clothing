test('TC02 navigation: menu drawer, category link, footer link, logo', async ({ page }) => {
  const state = await setup(page)
  await page.goto('/')
  const menuButton = page.getByRole('button', { name: 'Open menu' })
  await menuButton.click()
  const drawer = page.getByRole('dialog', { name: 'Menu' })
  await expect(drawer).toBeVisible()
  await expect.poll(() => page.evaluate(() => !!document.activeElement.closest('#menu-drawer'))).toBe(true)
  await page.keyboard.press('Escape')
  await expect(drawer).toBeHidden()
  await expect(menuButton).toBeFocused()
  await menuButton.click()
  await drawer.locator('summary', { hasText: 'Women’s fashion' }).click()
  await drawer.getByRole('link', { name: 'Skirts', exact: true }).click()
  await expect(page).toHaveURL(/\/women\/ready-to-wear\?categories=w-skirts$/)
  await expect(page.getByRole('heading', { level: 1, name: 'All women’s ready-to-wear' })).toBeVisible()
  await expect(page.getByRole('link', { name: 'QA skirt', exact: true })).toBeVisible()
  expect(state.call('/api/product-page', p => p.get('department') === 'women' && p.get('categories') === 'w-skirts').length).toBeGreaterThan(0)
  const footer = page.getByRole('contentinfo')
  const shop = footer.locator('summary', { hasText: 'Shop' })
  if (await shop.isVisible()) await shop.click() // mobile: footer dạng accordion
  await footer.getByRole('link', { name: 'Men’s fashion', exact: true }).click()
  await expect(page).toHaveURL(/\/men\/ready-to-wear$/)
  await page.getByRole('link', { name: 'N&B home' }).click()
  await expect(page).toHaveURL(/\/$/)
  await state.verify()
})

