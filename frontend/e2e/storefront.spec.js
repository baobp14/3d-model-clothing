test('TC04 filter and sort send the right parameters and update results', async ({ page }) => {
  const state = await setup(page)
  await page.goto('/men/ready-to-wear')
  await expect(page.getByRole('article')).toHaveCount(2)
  await page.getByRole('combobox').selectOption('priceDesc')
  await expect(page).toHaveURL(/sort=priceDesc/)
  await expect(page.getByRole('article').first()).toContainText('QA shirt')
  await page.getByRole('combobox').selectOption('priceAsc')
  await expect(page.getByRole('article').first()).toContainText('QA tee')
  await page.getByRole('button', { name: 'Filter', exact: true }).click()
  const drawer = page.getByRole('dialog', { name: 'Filters' })
  await expect(drawer.getByRole('button', { name: 'Unused red' })).toHaveCount(0) // chỉ màu đang có sản phẩm
  await drawer.getByRole('button', { name: 'Pearl white' }).click()
  await drawer.getByRole('button', { name: 'S', exact: true }).click()
  await expect(page.getByRole('article')).toHaveCount(2) // chưa áp dụng
  await drawer.getByRole('button', { name: 'View results' }).click()
  await expect(page).toHaveURL(/colors=white/)
  await expect(page).toHaveURL(/sizes=S/)
  await expect(page.getByRole('article')).toHaveCount(1)
  await expect(page.getByRole('button', { name: /^Filter\s*2$/ })).toBeVisible()
  expect(state.call('/api/product-page', p => p.get('colors') === 'white' && p.get('sizes') === 'S' && p.get('sort') === 'priceAsc').length).toBeGreaterThan(0)
  await page.getByRole('button', { name: 'Remove filter Pearl white' }).click()
  await expect(page).not.toHaveURL(/colors=/)
  await page.getByRole('button', { name: 'Clear filters' }).first().click()
  await expect(page.getByRole('article')).toHaveCount(2)
  await page.getByRole('button', { name: 'Shirts', exact: true }).click() // lối tắt danh mục
  await expect(page).toHaveURL(/categories=m-shirts/)
  await expect(page.getByRole('article')).toHaveCount(1)
  await state.verify()
})

